#!/usr/bin/env python3
"""Extracts the game rules from the single-file classroom page so both share one source of truth."""
import re,sys,os
src=sys.argv[1] if len(sys.argv)>1 else os.path.join(os.path.dirname(__file__),'..','castaway-economy.html')
h=open(src,encoding='utf-8').read()
s=re.search(r'<script>(.*?)</script>',h,re.S).group(1)
m=re.search(r'// ==LOGIC START==(.*?)// ==LOGIC END==',s,re.S).group(1)
names=sorted(set(re.findall(r'^function (\w+)',m,re.M))|set(re.findall(r'^(?:const|let|var) (\w+)\s*=',m,re.M)))
open(os.path.join(os.path.dirname(__file__),'logic.js'),'w',encoding='utf-8').write("// GENERATED by build-logic.py from the classroom page. Do not edit.\n"+m+"\nmodule.exports={"+",".join(names)+"};\n")
print('logic.js written,',len(names),'exports')
